// Dedicated mihomo instance for minimax2api registrations.
//
// WHY: trae2api's tests switch the shared Clash Verge selections, so two
// projects fighting over one "全部节点" group corrupt each other's exits.
// This instance is OURS alone: its own port (17897), its own REST controller
// (127.0.0.1:19097, plain TCP), config generated from Verge's active profile.
//
//   node tools/reg-proxy.mjs gen      # rebuild yaml from Verge active profile
//   node tools/reg-proxy.mjs start    # spawn mihomo + wait for controller
//   node tools/reg-proxy.mjs stop
//   node tools/reg-proxy.mjs now | list | select "🇯🇵JP-Reality" | status
import { spawn, execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const WORKDIR = path.join(HERE, ".reg-proxy");
const YAML = path.join(HERE, "reg-proxy.yaml");
const PIDFILE = path.join(WORKDIR, "mihomo.pid");
const PORT = 17897;
const CTRL = "http://127.0.0.1:19097";
const GROUP = "全部节点";
const MIHOMO = "F:\\Clash Verge\\verge-mihomo.exe";
const VERGE_DIR = "C:\\Users\\chen7447\\AppData\\Roaming\\io.github.clash-verge-rev.clash-verge-rev";
const VERGE_PROFILES = path.join(VERGE_DIR, "profiles.yaml");
const MMDB = path.join(VERGE_DIR, "Country.mmdb");

const cmd = process.argv[2] || "status";

async function api(method, apiPath, body = null) {
  const res = await fetch(CTRL + apiPath, {
    method,
    headers: { "Content-Type": "application/json" },
    body: body ? JSON.stringify(body) : null,
  });
  const text = await res.text();
  let json = null;
  try { json = JSON.parse(text); } catch {}
  return { status: res.status, json, text };
}

async function controllerUp() {
  try { return (await api("GET", "/version")).status === 200; } catch { return false; }
}

function activeProfileFile() {
  const meta = fs.readFileSync(VERGE_PROFILES, "utf8");
  const current = (meta.match(/^current:\s*(\S+)/m) || [])[1];
  if (!current) throw new Error("profiles.yaml 里没有 current");
  const itemRe = new RegExp(`- uid: ${current}[\\s\\S]*?file: (\\S+)`);
  const file = (meta.match(itemRe) || [])[1];
  if (!file) throw new Error(`找不到 current=${current} 对应的 profile 文件`);
  return path.join(VERGE_DIR, "profiles", file);
}

function gen() {
  const src = fs.readFileSync(activeProfileFile(), "utf8");
  // copy the `proxies:` section verbatim (flow-style YAML with credentials)
  const start = src.search(/^proxies:\s*$/m);
  if (start < 0) throw new Error("profile 里没有 proxies: 段");
  const rest = src.slice(start + "proxies:".length);
  const nextKey = rest.search(/^[a-z][a-z0-9-]*:\s*(#.*)?$/m);
  const proxiesBody = nextKey >= 0 ? rest.slice(0, nextKey) : rest;
  const names = [...proxiesBody.matchAll(/(?:^|\s)name:\s*("([^"]+)"|'([^']+)'|[^,\n}]+)/g)]
    .map((m) => (m[2] ?? m[3] ?? m[1]).trim())
    .filter((n) => n && !/^(DIRECT|REJECT)$/i.test(n) && !/剩余流量|套餐到期|官网|重置|到期/.test(n));
  if (!names.length) throw new Error("proxies 段解析不出节点名");
  const groupMembers = names.map((n) => `      - ${JSON.stringify(n)}`).join("\n");
  const out = `# generated by tools/reg-proxy.mjs gen — do not edit by hand
mixed-port: ${PORT}
external-controller: 127.0.0.1:${CTRL.split(":").pop()}
mode: rule
log-level: warning
ipv6: false

proxies:${proxiesBody}
proxy-groups:
  - name: ${GROUP}
    type: select
    proxies:
${groupMembers}

rules:
  - MATCH,${GROUP}
`;
  fs.mkdirSync(WORKDIR, { recursive: true });
  fs.writeFileSync(YAML, out);
  if (!fs.existsSync(path.join(WORKDIR, "Country.mmdb"))) {
    fs.copyFileSync(MMDB, path.join(WORKDIR, "Country.mmdb"));
  }
  console.log(`已生成 ${YAML}（${names.length} 个节点）`);
}

async function start() {
  if (await controllerUp()) { console.log("专属实例已在运行"); return; }
  if (!fs.existsSync(YAML)) gen();
  const child = spawn(MIHOMO, ["-f", YAML, "-d", WORKDIR], {
    stdio: "ignore",
    detached: true,
    windowsHide: true,
  });
  child.unref();
  fs.writeFileSync(PIDFILE, String(child.pid));
  for (let i = 0; i < 20; i += 1) {
    await new Promise((r) => setTimeout(r, 500));
    if (await controllerUp()) { console.log(`专属实例已启动 pid=${child.pid} ctrl=${CTRL} mixed=${PORT}`); return; }
  }
  throw new Error("专属实例 10 秒内没起来（看 " + WORKDIR + " 下日志/端口占用）");
}

async function stop() {
  try {
    const pid = Number(fs.readFileSync(PIDFILE, "utf8").trim());
    execFileSync("taskkill", ["/PID", String(pid), "/F"], { stdio: "ignore" });
    fs.rmSync(PIDFILE, { force: true });
    console.log(`已停止 pid=${pid}`);
  } catch { console.log("没有在运行的记录（或已停止）"); }
}

function exitIp() {
  try {
    return execFileSync("curl.exe", ["-s", "-m", "8", "-x", `http://127.0.0.1:${PORT}`, "https://api.ipify.org"], { encoding: "utf8" }).trim();
  } catch { return "?"; }
}

if (cmd === "gen") gen();
else if (cmd === "start") await start();
else if (cmd === "stop") await stop();
else if (cmd === "now") {
  const { json } = await api("GET", "/proxies");
  console.log(json.proxies[GROUP]?.now);
} else if (cmd === "list") {
  const { json } = await api("GET", "/proxies");
  for (const n of json.proxies[GROUP]?.all || []) console.log(n);
} else if (cmd === "select") {
  const name = process.argv.slice(3).join(" ");
  const r = await api("PUT", `/proxies/${encodeURIComponent(GROUP)}`, { name });
  console.log(`select ${name} -> ${r.status}`);
} else if (cmd === "status") {
  const up = await controllerUp();
  if (!up) { console.log("专属实例未运行"); process.exit(1); }
  const { json } = await api("GET", "/proxies");
  console.log(`running · now=${json.proxies[GROUP]?.now} · exit=${exitIp()}`);
} else {
  console.log("用法: gen | start | stop | now | list | select NAME | status");
}
